"""
ExecutionPlan — Typed pre-execution blueprint generated by RuntimePlanner before pipeline execution.
"""

from typing import Literal, Optional, Dict, Any
from pydantic import BaseModel, Field


class ExecutionPlan(BaseModel):
    """
    Typed, explainable plan containing explicit runtime parameters resolved
    by PolicyEngine and ConstraintEngine before executing retrieval or generation.
    """
    retrieval_strategy: str = Field(
        default="hybrid",
        description="Delegated to AdaptiveRetrievalRouter: 'bm25', 'computation', 'live_database', 'graph_rag', 'hybrid'."
    )
    retrieval_top_k: int = Field(default=10, ge=1, le=50)
    candidate_pool: int = Field(default=30, ge=5, le=100)
    rerank_top_n: int = Field(default=5, ge=1, le=20)
    reranking: bool = Field(default=True)
    graph_expansion: bool = Field(default=False)
    query_rewriting: bool = Field(default=True)
    context_compression: bool = Field(default=True)
    
    model: str = Field(default="groq/llama3-70b-8192")
    reasoning_effort: Literal["LOW", "STANDARD", "HIGH"] = Field(default="STANDARD")
    
    verification_level: Literal["BASIC", "STANDARD", "STRICT"] = Field(default="STANDARD")
    max_retries: int = Field(default=1, ge=0, le=3)
    latency_budget_ms: int = Field(default=3000, gt=0)
    cost_budget: float = Field(default=0.02, ge=0.0)
    
    reasoning: str = Field(
        default="Standard pipeline execution plan",
        description="Structured rationale explaining why these strategy decisions were selected."
    )

    def to_dict(self) -> Dict[str, Any]:
        """Export plan as plain dictionary."""
        return self.model_dump()
